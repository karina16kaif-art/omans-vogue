-- Existing IDs and defaults are retained. Supply a generator for the original
-- bundled schema, in which products.id was populated by Express.
do $$
declare
  id_column record;
  next_id numeric;
  sequence_name regclass;
  sequence_config record;
  sequence_last bigint;
  sequence_called boolean;
  largest_id bigint;
  incompatible_columns text;
begin
  select attnum, atttypid, attnotnull, attidentity, atthasdef into id_column
  from pg_attribute where attrelid = 'public.products'::regclass and attname = 'id' and not attisdropped;
  if not found or id_column.atttypid not in ('bigint'::regtype, 'integer'::regtype, 'smallint'::regtype)
    or not id_column.attnotnull then
    raise exception 'Review public.products.id: expected a non-null integer ID.';
  end if;
  if not exists (
    select 1 from pg_index where indrelid = 'public.products'::regclass
      and indisunique and indimmediate and indisvalid and indisready
      and indpred is null and indnkeyatts = 1 and indkey[0] = id_column.attnum
  ) then
    raise exception 'Review public.products.id: expected a valid unique index on the ID.';
  end if;

  select string_agg(expected.relation::text || '.' || expected.column_name, ', ') into incompatible_columns
  from (values
    ('public.products'::regclass, 'collections', 'text[]'::regtype),
    ('public.products'::regclass, 'images', 'text[]'::regtype),
    ('public.products'::regclass, 'variants', 'jsonb'::regtype),
    ('public.products'::regclass, 'stock', 'integer'::regtype),
    ('public.products'::regclass, 'stock_quantity', 'integer'::regtype),
    ('public.products'::regclass, 'catalog_version', 'bigint'::regtype),
    ('public.brand_settings'::regclass, 'storefront', 'jsonb'::regtype)
  ) as expected(relation, column_name, type)
  join pg_attribute a on a.attrelid = expected.relation and a.attname = expected.column_name and not a.attisdropped
  where a.atttypid <> expected.type;
  if incompatible_columns is not null then
    raise exception 'Review existing catalogue column types before migrating: %', incompatible_columns;
  end if;

  if id_column.attidentity = '' and not id_column.atthasdef then
    if exists (select 1 from pg_trigger where tgrelid = 'public.products'::regclass
      and not tgisinternal and tgenabled in ('O', 'A') and (tgtype & 7) = 7) then
      raise exception 'Review the existing products BEFORE INSERT trigger for ID generation.';
    end if;
    alter table public.products alter column id add generated by default as identity;
  end if;

  sequence_name := pg_get_serial_sequence('public.products', 'id')::regclass;
  if sequence_name is not null then
    select seqincrement, seqmax, seqcycle, seqcache into sequence_config
    from pg_sequence where seqrelid = sequence_name;
    if sequence_config.seqincrement <= 0 or sequence_config.seqcycle or sequence_config.seqcache <> 1 then
      raise exception 'Review the existing custom products ID sequence %.', sequence_name;
    end if;
    select max(id) into largest_id from public.products;
    execute format('select last_value, is_called from %s', sequence_name) into sequence_last, sequence_called;
    next_id := sequence_last::numeric + case when sequence_called then sequence_config.seqincrement else 0 end;
    if largest_id is not null and next_id <= largest_id then
      next_id := next_id + ceil((largest_id::numeric + 1 - next_id) / sequence_config.seqincrement)
        * sequence_config.seqincrement;
      if next_id <= sequence_config.seqmax then
        execute format('alter sequence %s restart with %s', sequence_name, next_id);
      end if;
    end if;
    if next_id > sequence_config.seqmax then
      raise exception 'The products ID sequence % is exhausted.', sequence_name;
    end if;
    execute format('revoke all on sequence %s from PUBLIC, anon, authenticated, service_role', sequence_name);
    execute format('grant usage on sequence %s to service_role', sequence_name);
    if has_sequence_privilege('anon', sequence_name, 'USAGE, SELECT, UPDATE')
       or has_sequence_privilege('authenticated', sequence_name, 'USAGE, SELECT, UPDATE') then
      raise exception 'Review inherited storefront grants on sequence %.', sequence_name;
    end if;
  end if;
end
$$;

-- Zero is a stored count and stays out of stock. NULL means untracked.
-- If both fields were already used, leave conflicting rows untouched and stop.
do $$
begin
  if exists (
    select 1 from public.products
    where stock is not null and stock_quantity is not null
      and stock is distinct from stock_quantity
  ) then
    raise exception 'Review conflicting product stock counts before migration.';
  end if;
end
$$;

update public.products
set stock = coalesce(stock, stock_quantity),
    stock_quantity = coalesce(stock_quantity, stock)
where stock is distinct from stock_quantity;

create or replace function public.omans_product_version()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.stock := coalesce(new.stock_quantity, new.stock);
    new.stock_quantity := new.stock;
  else
    if new.stock_quantity is distinct from old.stock_quantity then
      if new.stock is distinct from old.stock and new.stock is distinct from new.stock_quantity then
        raise exception 'Review conflicting product stock counts.';
      end if;
      new.stock := new.stock_quantity;
    else
      new.stock_quantity := new.stock;
    end if;
    new.catalog_version := old.catalog_version + 1;
  end if;

  if tg_op = 'INSERT' or new.stock_quantity is distinct from old.stock_quantity
     or new.variants is distinct from old.variants or new.in_stock is distinct from old.in_stock then
    new.stock_status := case
      when new.in_stock is false or new.archived_at is not null then 'out_of_stock'
      when pg_catalog.jsonb_array_length(coalesce(new.variants, '[]'::jsonb)) > 0 then
        case when exists (
          select 1 from pg_catalog.jsonb_array_elements(new.variants) as v(item)
          where (v.item->>'stockQuantity')::integer > 0
        ) then 'in_stock' else 'out_of_stock' end
      when new.stock_quantity <= 0 then 'out_of_stock'
      else 'in_stock'
    end;
  end if;
  return new;
end
$$;

revoke all on function public.omans_product_version() from PUBLIC, anon, authenticated;
grant execute on function public.omans_product_version() to service_role;
drop trigger if exists omans_product_version on public.products;
create trigger omans_product_version before insert or update on public.products
for each row execute function public.omans_product_version();

-- AFTER INSERT runs only for a newly stored checkout. A duplicate request
-- does not consume stock, and a failed stock check rolls back the entire order.
create or replace function public.omans_reserve_order_inventory()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  line jsonb;
  product public.products%rowtype;
  option_index integer;
  chosen jsonb;
  requested integer;
  remaining integer;
  current_price numeric;
begin
  for line in select item
    from pg_catalog.jsonb_array_elements(new.items::jsonb) as lines(item)
    order by (item->>'productId')::bigint, item->>'variantId'
  loop
    requested := (line->>'quantity')::integer;
    select * into product from public.products where id = (line->>'productId')::bigint for update;
    if not found or product.archived_at is not null or product.in_stock is false or requested is null or requested < 1 then
      raise exception 'omans_checkout_catalogue_changed';
    end if;

    if pg_catalog.jsonb_array_length(coalesce(product.variants, '[]'::jsonb)) > 0 then
      select entry, (position - 1)::integer into chosen, option_index
      from pg_catalog.jsonb_array_elements(product.variants) with ordinality as options(entry, position)
      where entry->>'id' = line->>'variantId';
      if not found then raise exception 'omans_checkout_catalogue_changed'; end if;
      current_price := coalesce((chosen->>'salePrice')::numeric, (chosen->>'price')::numeric);
      remaining := (chosen->>'stockQuantity')::integer - requested;
    else
      if line->>'variantId' is not null then raise exception 'omans_checkout_catalogue_changed'; end if;
      current_price := coalesce(product.sale_price, product.price);
      remaining := product.stock_quantity - requested;
    end if;

    if current_price is null or current_price <= 0 or remaining < 0
       or pg_catalog.round(current_price, 2) is distinct from (line->>'unitPrice')::numeric then
      raise exception 'omans_checkout_catalogue_changed';
    end if;

    if pg_catalog.jsonb_array_length(coalesce(product.variants, '[]'::jsonb)) > 0 then
      if remaining is null then raise exception 'omans_checkout_catalogue_changed'; end if;
      update public.products
      set variants = pg_catalog.jsonb_set(product.variants, array[option_index::text, 'stockQuantity'], pg_catalog.to_jsonb(remaining))
      where id = product.id;
    elsif remaining is not null then
      update public.products set stock_quantity = remaining where id = product.id;
    end if;
  end loop;
  return new;
end
$$;

revoke all on function public.omans_reserve_order_inventory() from PUBLIC, anon, authenticated;
grant execute on function public.omans_reserve_order_inventory() to service_role;
drop trigger if exists omans_reserve_order_inventory on public.orders;
create trigger omans_reserve_order_inventory after insert on public.orders
for each row when (new.checkout_request_id is not null) execute function public.omans_reserve_order_inventory();

-- Only product IDs and confirmed unit totals are returned to the API.
create or replace function public.omans_confirmed_bestsellers()
returns table (product_id text, units bigint)
language sql
stable
security invoker
set search_path = ''
as $$
  select p.id::text, sum((l.item->>'quantity')::bigint)::bigint
  from public.orders o
  cross join lateral pg_catalog.jsonb_array_elements(
    case when pg_catalog.jsonb_typeof(o.items::jsonb) = 'array' then o.items::jsonb else '[]'::jsonb end
  ) l(item)
  join public.products p on p.id::text = coalesce(l.item->>'productId', l.item->>'id')
  where o.admin_payment_verified_at is not null and p.archived_at is null
    and (l.item->>'quantity') ~ '^[1-9][0-9]{0,8}$'
  group by p.id
  order by sum((l.item->>'quantity')::bigint) desc, p.id
  limit 24;
$$;

revoke all on function public.omans_confirmed_bestsellers() from PUBLIC, anon, authenticated;
grant execute on function public.omans_confirmed_bestsellers() to service_role;
notify pgrst, 'reload schema';
commit;
