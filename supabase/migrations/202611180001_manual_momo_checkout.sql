-- Check the live schema while the migration holds the table lock. No rows are rewritten.
do $$
declare
  id_column record;
  key_column record;
  sequence_name regclass;
  sequence_config record;
  sequence_last bigint;
  sequence_called boolean;
  largest_id bigint;
  next_id numeric;
  status_column record;
  required_columns text;
begin
  select attnum, atttypid, attnotnull, attidentity, atthasdef into id_column
  from pg_attribute where attrelid = 'public.orders'::regclass and attname = 'id' and not attisdropped;

  if not found or id_column.atttypid <> 'bigint'::regtype or not id_column.attnotnull then
    raise exception 'public.orders.id must already be bigint NOT NULL. Existing IDs will not be converted.';
  end if;

  if not exists (
    select 1 from pg_attribute
    where attrelid = 'public.orders'::regclass and attname = 'admin_payment_verified_at' and not attisdropped
      and atttypid = 'timestamptz'::regtype and not attnotnull and not atthasdef
  ) then
    raise exception 'orders.admin_payment_verified_at must be a nullable timestamptz without a default.';
  end if;

  for key_column in
    select attnum, attname, atttypid from pg_attribute
    where attrelid = 'public.orders'::regclass and attname in ('id', 'checkout_request_id') and not attisdropped
  loop
    if key_column.attname = 'checkout_request_id' and key_column.atttypid <> 'uuid'::regtype then
      raise exception 'public.orders.checkout_request_id must be uuid.';
    end if;
    if not exists (
      select 1 from pg_index where indrelid = 'public.orders'::regclass
        and indisunique and indimmediate and indisvalid and indisready
        and indpred is null and indnkeyatts = 1 and indkey[0] = key_column.attnum
    ) then
      execute format('create unique index %I on public.orders (%I)',
        'omans_orders_' || key_column.attname || '_key', key_column.attname);
    end if;
  end loop;

  if id_column.attidentity = '' and not id_column.atthasdef then
    if exists (
      select 1 from pg_trigger
      where tgrelid = 'public.orders'::regclass and not tgisinternal
        and tgenabled in ('O', 'A') and (tgtype & 7) = 7
    ) then
      raise exception 'orders.id has no default and orders has a BEFORE INSERT trigger. Review the trigger for ID generation first.';
    end if;
    alter table public.orders alter column id add generated by default as identity;
  end if;

  sequence_name := pg_get_serial_sequence('public.orders', 'id')::regclass;
  if sequence_name is not null then
    select seqincrement, seqmax, seqcycle, seqcache into sequence_config
    from pg_sequence where seqrelid = sequence_name;

    if sequence_config.seqincrement <= 0 or sequence_config.seqcycle or sequence_config.seqcache <> 1 then
      raise exception 'Review the existing custom orders ID sequence % before applying this migration.', sequence_name;
    end if;

    select max(id) into largest_id from public.orders;
    execute format('select last_value, is_called from %s', sequence_name) into sequence_last, sequence_called;
    next_id := sequence_last::numeric + case when sequence_called then sequence_config.seqincrement else 0 end;
    if largest_id is not null and next_id <= largest_id then
      next_id := next_id + ceil((largest_id::numeric + 1 - next_id) / sequence_config.seqincrement)
        * sequence_config.seqincrement;
      if next_id <= sequence_config.seqmax then
        execute format('alter sequence %s restart with %s', sequence_name, next_id);
      end if;
    end if;
    if next_id > sequence_config.seqmax then
      raise exception 'The orders ID sequence % has no available IDs above the current range.', sequence_name;
    end if;
    execute format('revoke all on sequence %s from PUBLIC, anon, authenticated, service_role', sequence_name);
    execute format('grant usage on sequence %s to service_role', sequence_name);
    if has_sequence_privilege('anon', sequence_name, 'USAGE, SELECT, UPDATE')
       or has_sequence_privilege('authenticated', sequence_name, 'USAGE, SELECT, UPDATE') then
      raise exception 'Review inherited storefront grants on sequence %.', sequence_name;
    end if;
  end if;

  -- Preserve existing defaults. Supply a pending default only where it is absent
  -- and the column needs one for inserts by this backend.
  for status_column in
    select a.attname, a.attnotnull, a.atthasdef,
           pg_get_expr(d.adbin, d.adrelid) as default_expression
    from pg_attribute a
    left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = 'public.orders'::regclass and not a.attisdropped
      and a.attname in ('status', 'payment_status')
  loop
    if not status_column.atthasdef and (status_column.attname = 'status' or status_column.attnotnull) then
      execute format('alter table public.orders alter column %I set default %L', status_column.attname, 'pending');
    elsif status_column.attname = 'payment_status' and status_column.atthasdef
      and status_column.default_expression !~* '^''(pending|unpaid)''(::.+)?$'
      and status_column.default_expression !~* '^NULL(::.+)?$'
    then
      raise exception 'Review the existing orders.payment_status default before checkout. New payments must start unverified.';
    end if;
  end loop;

  select string_agg(attname, ', ' order by attname) into required_columns
  from pg_attribute
  where attrelid = 'public.orders'::regclass and attnum > 0 and not attisdropped
    and attnotnull and not atthasdef and attidentity = '' and attgenerated = ''
    and attname not in (
      'id', 'customer_name', 'customer_email', 'customer_phone', 'delivery_phone',
      'delivery_address', 'city_region', 'items', 'total', 'total_amount', 'order_status', 'payment_method',
      'fulfilment_method', 'delivery_fee', 'momo_phone', 'payment_reference',
      'whatsapp_number', 'checkout_request_id', 'checkout_request_hash', 'created_at', 'updated_at'
    );
  if required_columns is not null then
    raise exception 'Additional required orders columns need a checkout value or a database default: %', required_columns;
  end if;
end
$$;

