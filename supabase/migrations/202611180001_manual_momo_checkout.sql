-- Do not change any role memberships automatically. Abort on inherited grants
-- that would leave a customer API role with direct access.
do $$
declare
  remaining_grants text;
begin
  if not exists (select 1 from pg_roles where rolname = 'service_role' and rolbypassrls) then
    raise exception 'The Express backend requires a service_role with BYPASSRLS.';
  end if;
  if exists (
    select 1 from pg_roles r where r.rolname in ('anon', 'authenticated')
      and (r.rolbypassrls or r.rolsuper or pg_has_role(r.oid, 'service_role', 'MEMBER'))
  ) then
    raise exception 'Review elevated role memberships for anon and authenticated.';
  end if;

  select string_agg(r.rolname || ' on ' || c.relname, ', ') into remaining_grants
  from pg_class c cross join pg_roles r
  where c.oid in ('public.orders'::regclass, 'public.admin_credentials'::regclass,
                  'public.products'::regclass, 'public.brand_settings'::regclass)
    and r.rolname in ('anon', 'authenticated')
    and (
      has_table_privilege(r.oid, c.oid, 'SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER')
      or has_any_column_privilege(r.oid, c.oid, 'SELECT, INSERT, UPDATE, REFERENCES')
    );
  if remaining_grants is not null then
    raise exception 'Review inherited storefront grants before migrating: %', remaining_grants;
  end if;
end
$$;

