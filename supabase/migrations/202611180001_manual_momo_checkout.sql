create or replace function public.omans_sync_delivery_fee()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.delivery_fee := coalesce(new.campus_delivery_fee, new.delivery_fee, 10);
    new.campus_delivery_fee := new.delivery_fee;
  elsif new.campus_delivery_fee is distinct from old.campus_delivery_fee then
    if new.delivery_fee is distinct from old.delivery_fee
       and new.delivery_fee is distinct from new.campus_delivery_fee then
      raise exception 'Review conflicting brand delivery fees.';
    end if;
    new.delivery_fee := new.campus_delivery_fee;
  else
    new.campus_delivery_fee := new.delivery_fee;
  end if;
  return new;
end
$$;

revoke all on function public.omans_sync_delivery_fee() from PUBLIC, anon, authenticated;
grant execute on function public.omans_sync_delivery_fee() to service_role;
drop trigger if exists omans_sync_delivery_fee on public.brand_settings;
create trigger omans_sync_delivery_fee before insert or update of delivery_fee, campus_delivery_fee
on public.brand_settings for each row execute function public.omans_sync_delivery_fee();

